test('editor prikazuje formatiranje promijenjeno tipkovnicom i odbija nesiguran link', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Nova bilješka', exact: true }).click()
  const body = page.getByRole('textbox', { name: 'Sadržaj bilješke' })
  await body.fill('Tekst bilješke')
  await body.press('Control+b')
  await expect(page.getByRole('button', { name: 'Podebljano' })).toHaveAttribute('aria-pressed', 'true')
  await body.press('Control+b')
  await expect(page.getByRole('button', { name: 'Podebljano' })).toHaveAttribute('aria-pressed', 'false')
  const dialogs: string[] = []
  page.on('dialog', async dialog => {
    dialogs.push(dialog.type())
    await dialog.accept(dialog.type() === 'prompt' ? 'javascript:alert(1)' : undefined)
  })
  await page.getByRole('button', { name: 'Dodaj ili ukloni link' }).click()
  await expect.poll(() => dialogs).toEqual(['prompt', 'alert'])
  await expect(body.locator('a')).toHaveCount(0)
  await expect(body).toContainText('Tekst bilješke')
})

