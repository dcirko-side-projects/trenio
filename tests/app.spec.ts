test('dijalozi imaju naziv, početni fokus i rade tipkovnicom', async ({ page }) => {
  await page.goto('/')
  const addTask = page.getByRole('button', { name: 'Dodaj zadatak', exact: true })
  await addTask.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Zadatak', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('Naziv zadatka')).toBeFocused()
  // Background controls are inert while the native modal dialog is open.
  await addTask.evaluate(element => element.focus())
  await expect(dialog.getByLabel('Naziv zadatka')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByLabel('Kategorija', { exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByLabel('Naziv zadatka')).toBeFocused()
  await page.screenshot({ path: `test-results/dialog-${test.info().project.name}.png`, fullPage: true })
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(addTask).toBeFocused()

  await page.getByRole('navigation', { name: /Glavna navigacija|Mobilna navigacija/ }).getByRole('button', { name: 'Kategorije', exact: true }).click()
  const addCategory = page.getByRole('button', { name: 'Nova kategorija', exact: true })
  await addCategory.focus()
  await page.keyboard.press('Enter')
  const category = page.getByRole('dialog', { name: 'Nova kategorija', exact: true })
  await expect(category.getByLabel('Naziv', { exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(category).not.toBeVisible()
  await expect(addCategory).toBeFocused()
})

