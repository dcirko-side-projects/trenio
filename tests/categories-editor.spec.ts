for (const kind of ['bilješke', 'plana']) test(`editor ${kind}: fokus, kursor, više checkboxova, novi redovi, brisanje i ponovno otvaranje`, async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: kind === 'plana' ? 'Novi plan' : 'Nova bilješka', exact: true }).click()
  await page.getByLabel(kind === 'plana' ? 'Naziv plana' : 'Naslov bilješke').fill('Mobilni unos')
  const body = page.getByRole('textbox', { name: `Sadržaj ${kind}` })
  await body.fill('prvi redak')
  await body.press('End')
  await page.evaluate(() => {
    const state = window as unknown as { editorNode: Element; optionUpdates: number; editorBlurs: number }
    const element = document.querySelector('.note-body') as HTMLElement & { editor: Editor }
    state.editorNode = element; state.optionUpdates = 0; state.editorBlurs = 0
    const original = element.editor.setOptions.bind(element.editor)
    element.editor.setOptions = options => { state.optionUpdates++; original(options) }
    element.addEventListener('blur', () => { state.editorBlurs++ })
  })
  await page.getByRole('button', { name: kind === 'plana' ? 'Pretvori redak u korak plana' : 'Pretvori redak u checkbox', exact: true }).click()
  await expect(body).toBeFocused()
  await expect(body).toHaveAttribute('autocapitalize', 'off')
  await page.keyboard.type(' nastavak')
  await page.keyboard.press('Enter')
  await page.keyboard.type('drugi redak')
  await page.keyboard.press('Enter')
  await page.keyboard.type('treci')
  await page.keyboard.press('Backspace')
  await page.keyboard.type('i redak')
  await expect(body.locator('li')).toHaveCount(3)
  await expect(body.locator('li').nth(0)).toContainText('prvi redak nastavak')
  await expect(body.locator('li').nth(2)).toContainText('treci redak')
  expect(await page.evaluate(() => (window as unknown as { editorNode: Element }).editorNode === document.querySelector('.note-body'))).toBe(true)
  expect(await page.evaluate(() => ({ updates: (window as unknown as { optionUpdates: number }).optionUpdates, blurs: (window as unknown as { editorBlurs: number }).editorBlurs }))).toEqual({ updates: 0, blurs: 0 })
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await page.keyboard.type('obican tekst')
  await expect(body.locator('li')).toHaveCount(3)
  await body.getByRole('checkbox').nth(1).check()
  await page.getByRole('checkbox', { name: 'Prikvači u Trenutno', exact: true }).check()
  await page.getByRole('button', { name: 'Spremi', exact: true }).click()
  await page.getByRole('button', { name: 'Trenutno', exact: true }).click()
  await page.getByRole('button', { name: /Mobilni unos/ }).click()
  await expect(body).toHaveAttribute('autocapitalize', 'off')
  await expect(body.getByRole('checkbox')).toHaveCount(3)
  await expect(body.getByRole('checkbox').nth(1)).toBeChecked()
  await expect(body).toContainText('obican tekst')
  if (test.info().project.name !== 'desktop') expect(await page.getByRole('dialog').evaluate(element => Math.round(element.getBoundingClientRect().top))).toBe(0)
  await page.screenshot({ path: `.local/ui-review/checklist-${kind}-${test.info().project.name}.png`, fullPage: false })
})

test('Enter u povezanom checkboxu ne kopira vezu u novi redak', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Trenutno', exact: true }).click()
  await page.getByRole('button', { name: /Prostor za sljedeću ideju/ }).click()
  await page.getByRole('button', { name: 'Stvori povezani zadatak' }).click()
  const body = page.getByRole('textbox', { name: 'Sadržaj bilješke' })
  await body.locator('li p').click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await page.keyboard.type('novi neovisni checkbox')
  await expect(body.locator('li[data-task-id]')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Otvori povezani zadatak' })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Stvori povezani zadatak' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Spremi', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
