test('povratak vraća proširene podkategorije i pomicanje popisa', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('navigation', { name: /Glavna navigacija|Mobilna navigacija/ }).getByRole('button', { name: 'Kategorije', exact: true }).click()
  await page.getByRole('button', { name: /^Posao/ }).click()
  await page.getByRole('button', { name: 'Nova podkategorija', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Naziv', { exact: true }).fill('Povratak')
  await page.getByRole('button', { name: 'Dodaj', exact: true }).click()
  await page.getByRole('button', { name: 'Sve kategorije', exact: true }).click()
  await page.getByRole('button', { name: 'Proširi podkategorije: Posao' }).click()
  // Give every viewport a genuinely scrollable list, without creating private data.
  await page.addStyleTag({ content: '.category-row { min-height: 800px; }' })
  const child = page.getByRole('button', { name: /^Povratak/ })
  await child.scrollIntoViewIfNeeded()
  const scroll = await page.evaluate(() => window.scrollY)
  expect(scroll).toBeGreaterThan(0)
  await child.click()
  await expect(page.getByRole('heading', { name: 'Posao / Povratak', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Sažmi podkategorije: Posao' })).toHaveAttribute('aria-expanded', 'true')
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(scroll)
  await expect(child).toBeVisible()
})

