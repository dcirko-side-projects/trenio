import { expect, test } from '@playwright/test'

test('Natrag vraća tab, pretragu, filtar, kategoriju i otvoreni zapis', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Trenutno', exact: true }).click()
  await page.getByRole('button', { name: 'Otvori pretragu' }).click()
  await page.getByLabel('Pretraži sadržaj').fill('Posao')
  await page.getByLabel('Uključi arhivu').check()
  await page.getByRole('button', { name: 'Otvori kategoriju: Posao', exact: true }).click()
  await page.getByRole('button', { name: 'Dodaj zadatak', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Posao', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByLabel('Pretraži sadržaj')).toHaveValue('Posao')
  await expect(page.getByLabel('Uključi arhivu')).toBeChecked()
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Trenutno', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goForward()
  await expect(page.getByLabel('Pretraži sadržaj')).toHaveValue('Posao')
  await expect(page.getByLabel('Uključi arhivu')).toBeChecked()
})

test('odbijanje povratka čuva nacrt, a zatvaranje ne ostavlja lažni korak povijesti', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Trenutno', exact: true }).click()
  await page.getByRole('button', { name: 'Dodaj zadatak', exact: true }).click()
  await page.getByLabel('Naziv zadatka').fill('Sačuvaj nacrt')
  page.once('dialog', dialog => dialog.dismiss())
  await page.goBack()
  await expect(page.getByLabel('Naziv zadatka')).toHaveValue('Sačuvaj nacrt')
  await expect.poll(() => page.evaluate(() => window.history.state.index)).toBe(2)
  page.once('dialog', dialog => dialog.accept())
  await page.goBack()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Dodaj zadatak', exact: true }).click()
  await page.getByRole('button', { name: 'Zatvori uređivanje' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Danas', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

